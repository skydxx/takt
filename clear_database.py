#!/usr/bin/env python3
"""
Скрипт для ПОЛНОГО удаления базы данных
ВНИМАНИЕ: Удаляет ВЕСЬ файл базы данных!
"""

import os

DB_PATH = 'salary_bot.db'

def delete_database():
    """Полное удаление файла базы данных"""
    
    if not os.path.exists(DB_PATH):
        print("ℹ️  База данных не найдена (это нормально, будет создана при запуске бота)")
        return
    
    print("🔥 ВНИМАНИЕ! Это ПОЛНОСТЬЮ удалит файл базы данных!")
    print("")
    print("❌ Будет удалено ВСЁ:")
    print("   - Все смены (активные и закрытые)")
    print("   - Все работники")
    print("   - Все чаты")
    print("   - Все настройки чатов")
    print("   - Персональные ставки")
    print("   - История сообщений")
    print("")
    print("📝 После удаления нужно будет:")
    print("   1. Запустить бота (база создастся автоматически)")
    print("   2. В АДМИНСКОМ ЧАТЕ: /setchat <chat_id> <название>")
    print("   3. Настроить условия: /setjob <номер> <ставка> <время>")
    print("")
    
    answer = input("Вы АБСОЛЮТНО уверены? Введите 'УДАЛИТЬ' для подтверждения: ")
    
    if answer != 'УДАЛИТЬ':
        print("❌ Отменено")
        return
    
    try:
        os.remove(DB_PATH)
        print("\n✅ База данных полностью удалена!")
        print("\n🚀 Теперь запустите бота:")
        print("   python3 salary_bot.py")
        print("\n💡 База данных создастся автоматически при первом запуске")
        
    except Exception as e:
        print(f"❌ Ошибка при удалении: {e}")

if __name__ == '__main__':
    delete_database()
